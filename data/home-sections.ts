const productSubgroupIds: Record<string, string[]> = {
  "almig-premium": ["almig-premium"],
  "oil-free": ["almig-premium"],
  "integrated-laser": ["almig-premium"],
  "rotorcomp-screw": ["rotorcomp-screw"],
};

export function getProductArticle(product: Product) {
  const section = homeSections.find((item) => item.categoryId === product.categoryId);
  if (!section) return null;

  const preferredTables = new Set([
    ...(product.tableIds ?? []),
    ...(productSubgroupIds[product.id] ?? []),
  ]);

  const subgroup = section.subgroups?.find((group) =>
    group.tableIds?.some((id) => preferredTables.has(id)),
  );

  const tableIds = [
    ...new Set([
      ...(product.tableIds ?? []),
      ...(subgroup?.tableIds ?? []),
      ...(section.tableIds ?? []),
    ]),
  ];

  return { section, subgroup, tableIds };
}
