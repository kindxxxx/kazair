export function localizeCategory<T extends { id: CategoryId; name: string; intro: string }>(
  category: T,
  locale: Locale,
): T {
  if (locale === "ru") return category;
  const copy = categoriesKk[category.id];
  return { ...category, name: copy.name, intro: copy.intro };
}

export function localizeCategories(locale: Locale) {
  return categories.map((item) => localizeCategory(item, locale));
}

export function localizeProduct(product: Product, locale: Locale): Product {
  if (locale === "ru") return product;
  const copy = productsKk[product.id];
  const categoryName = categoriesKk[product.categoryId].name;

  return {
    ...product,
    name: copy?.name ?? product.name,
    description: copy?.description ?? product.description,
    body: copy?.body ?? product.body,
    category: categoryName,
    specifications: product.specifications.map((item) => ({
      label: specLabelsKk[item.label] ?? item.label,
      value: specValuesKk[item.value] ?? item.value,
    })),
  };
}

export function productSearchText(product: Product) {
  const kk = localizeProduct(product, "kk");
  return [
    product.name,
    product.category,
    product.description,
    product.manufacturer,
    product.typeName,
    ...(product.types ?? []),
    ...(product.manufacturers ?? []),
    kk.name,
    kk.category,
    kk.description,
  ]
    .filter(Boolean)
    .join(" ")
    .toLowerCase();
}
